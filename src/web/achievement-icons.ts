/** One run of equal ink along a row: `width` pixels from (`x`, `y`), full ink or half. */
export interface IconRun {
  readonly x: number;
  readonly y: number;
  readonly width: number;
  readonly half: boolean;
}

/** An icon's grid, or the fallback's for an id with none (an own key only: never "toString"). */
function gridOf(id: string): readonly string[] {
  return (Object.hasOwn(ACHIEVEMENT_ICONS, id) && ACHIEVEMENT_ICONS[id]) || FALLBACK_ICON;
}

/** The icon as runs: along each row, every stretch of the same ink, merged into one. */
export function iconRuns(id: string): IconRun[] {
  const runs: IconRun[] = [];
  gridOf(id).forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const ink = row[x];
      if (ink !== "#" && ink !== "+") {
        x++;
        continue;
      }
      let end = x + 1;
      while (row[end] === ink) end++;
      runs.push({ x, y, width: end - x, half: ink === "+" });
      x = end;
    }
  });
  return runs;
}

/** The icon as an inline svg in `currentColor`, 16 px square; a caller's CSS sets its size on screen. */
export function iconSvg(id: string, doc: Document = document): SVGSVGElement {
  const svg = doc.createElementNS(SVG_NS, "svg");
  svg.setAttribute("viewBox", `0 0 ${ICON_SIZE} ${ICON_SIZE}`);
  svg.setAttribute("width", String(ICON_SIZE));
  svg.setAttribute("height", String(ICON_SIZE));
  svg.setAttribute("shape-rendering", "crispEdges");
  svg.setAttribute("aria-hidden", "true");
  svg.setAttribute("focusable", "false");
  svg.setAttribute("class", "pixel-icon");
  for (const run of iconRuns(id)) {
    const rect = doc.createElementNS(SVG_NS, "rect");
    rect.setAttribute("x", String(run.x));
    rect.setAttribute("y", String(run.y));
    rect.setAttribute("width", String(run.width));
    rect.setAttribute("height", "1");
    rect.setAttribute("fill", "currentColor");
    if (run.half) rect.setAttribute("fill-opacity", HALF_INK_OPACITY);
    svg.append(rect);
  }
  return svg;
}
